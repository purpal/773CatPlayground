package com.purpal.catplayground.nova

import com.purpal.catplayground.shooter.model.*

/** Nova owns its script; the original shooter's dialogue is untouched. */
fun novaOutro(stage: StageDef, cat: CatType): List<DialogLine> {
    fun pilot(text: String) = DialogLine(Speaker.CAT, text)
    fun boss(text: String) = DialogLine(Speaker.BOSS, text)
    if (stage.number == 2) return listOf(
        boss("骨刃外掛已脫離，主砲停機。櫻花防線……竟然被你突破了。"),
        pilot(if(cat==CatType.ORANGE) "橘曜收束火控。你的駕駛艙還完整，別急著跳船。" else "玄影解除鎖定。剛才那一擊，已經避開你的駕駛艙。"),
        boss("那道貓吼紋章……不是新式武器。古代核心真的回應你了？"),
        pilot("它為什麼甦醒，我們也在找答案。把下一座訊號塔的座標交給我。"),
        boss("座標已上傳。前方的守衛不會留手——帶著你的機體回來，喵航駕駛員。"),
        pilot("收到。保管好這片天空，我們還會再見。"),
    )
    if(stage.number==3) return listOf(
        boss("熔蜜鑽已脫離，蜂群鏈路歸零。你竟然撐過了要塞的最後一道爪擊。"),
        pilot(if(cat==CatType.ORANGE)"橘曜護甲還能撐。你的重砲很硬，但每次回收鑽頭，都會留下空隙。"else"玄影已退出射界。力量再大，只要讀懂掃掠節奏，就能找到航路。"),
        boss("我守的不是蜂蜜，是楓林底下那座古代反應爐。最近它一直在呼喚同類。"),
        pilot("我們的核心也收到了回聲。下一個訊號，來自亞馬遜水域。"),
        boss("帶上這份熱流圖。卡皮掌管那裡的冷卻中樞——別被他的平靜騙了。"),
        pilot("熱流資料已接收。銅鬃要塞，感謝指引。"),
    )
    if(stage.number==4) return listOf(
        boss("水砲卸壓，肩甲鎖定解除。嗯……冷卻曲線終於恢復正常了。"),
        pilot("你剛才增裝雙砲時，可不像只是在檢查冷卻系統。"),
        boss("壓力太高，就得找個出口。你的機體承受住了，古代核心也認可了你。"),
        pilot(if(cat==CatType.ORANGE)"橘曜已記錄雙砲參數。下次想測試，先用通訊頻道說一聲。"else"玄影已記錄水柱交叉點。下次測試，我會提早一步繞到你的背後。"),
        boss("呵。下一段航路的密鑰已送出。記得讓反應爐休息，力量不是一直加壓。"),
        pilot("收到。核心溫度穩定，繼續遠征。"),
    )
    if(stage.number==5) return listOf(
        boss("月躍停止跳躍，膝部散熱鎖解除。你竟然每次都能離開我的落點。"),
        pilot(if(cat==CatType.ORANGE)"橘曜的裝甲不是拿來硬接的。你的雷達一鎖定，我就知道該往哪裡走。"else"玄影只需要一步。你在空中改不了落點，落地後也藏不住散熱口。"),
        boss("輪組展成雙足，換來的是爆發力，也讓冷卻系統暴露了。這次你讀懂了月躍。"),
        pilot("那就把試驗場的古代訊號交給我們。它與機體變形時的共振完全一致。"),
        boss("資料已上傳。還有一份來自南極的封鎖通報——那裡的冰障不會替你讓路。"),
        pilot("收到。落點資料存檔，繼續追查核心訊號。"),
    )
    if(stage.number==6) return listOf(
        boss("霜脊雙體平台停機。冰障投射器熄火，南極航道重新開放。"),
        pilot(if(cat==CatType.ORANGE)"橘曜先拆投射器，再穿過缺口。再厚的冰，也得留下回收熱量的出口。"else"玄影已穿越最後一列冰障。錯開的通道，仍然有相通的航線。"),
        boss("你沒有追著舷砲亂跑，而是等到冰層解除。懂得等待，才是真正的艦長。"),
        pilot("我們不是來奪艦的。海床深處的古代訊號，最近是否也在增強？"),
        boss("每次展開雙船體，核心都會回應它。聲納記錄已送給你，請查清楚它在呼喚誰。"),
        pilot("記錄接收完成。保持航道暢通，我們會帶答案回來。"),
    )
    if(stage.number==7) return listOf(
        boss("眠巢錨足解除武裝，兩側電容歸零。你選擇了最難判斷的那條航線。"),
        pilot(if(cat==CatType.ORANGE)"橘曜不能同時打所有目標。我先拆蓄能電容，再等核心開艙。"else"玄影記下了開艙時間。電容開始鎖定前，足夠我再打一次核心。"),
        boss("母艦落地後，弱點改在左右兩側。你沒有把展開的支架當成新的武器。"),
        pilot("因為真正危險的是儲存的能量。古代訊號也是靠這些電容放大的嗎？"),
        boss("正是。南方港灣的雙潮姊妹接收了另一半訊號，帶著這份相位記錄去找她們。"),
        pilot("記錄已存檔。讓反應爐休息吧，眠巢司令。"),
    )
    if(stage.number==8) return listOf(
        boss("啾啾：雙潮對接鎖停機。嚕嚕：聲納浮標回收，兩艘船都安全。"),
        pilot(if(cat==CatType.ORANGE)"橘曜確認停火。魚雷從一側來，浮標從另一側來，我可不會只盯著船頭。"else"玄影確認停火。潛航的尾流出賣了換位，對接後的舷門也會暴露核心。"),
        boss("嚕嚕：合體後共用能源，連破損也一起承擔。啾啾：但你避開了我們的駕駛艙。"),
        pilot("我們追的是深海訊號，不是你們。這份眠巢相位記錄，能與聲納資料接起來嗎？"),
        boss("啾啾：可以，座標已解碼。嚕嚕：後面的守衛還有各自的祕密，別只用同一套戰術。"),
        pilot("雙潮航道已開放。導航同步，前往下一座訊號塔。"),
    )
    if(stage.number==9) return listOf(
        boss("玄竹履帶停轉，球殼解除鎖定。最後一座供能柱也離線了。"),
        pilot(if(cat==CatType.ORANGE)"橘曜先切斷補給，再等你停轉。裝甲再厚，也不能一邊修復一邊追著我跑。"else"玄影只看鎖定的反彈路線。你每一次改變方向，早就寫在預告裡。"),
        boss("球殼可以承受撞擊，卻藏不住停轉時的散熱口。這是守備試驗，不是無敵的堡壘。"),
        pilot("我們的圖騰核心在反彈時收到另一道回聲，像是同一個訊號重複了三次。"),
        boss("那是時差中繼站的閘門訊號。別追著慢彈跑，先看它們什麼時候離開力場。"),
        pilot("收到。供能紀錄封存，航路轉向雨林。"),
    )
    if(stage.number==10) return listOf(
        boss("時序環已收束，三道閘門全部關閉。這次……是你先讀懂了時鐘。"),
        pilot(if(cat==CatType.ORANGE)"橘曜沒有跟著慢下來。我等到閘門亮起，再離開下一批彈群的路線。"else"玄影只記釋放順序。展環後速度變了，但每一批放行前仍有預告。"),
        boss("我能改變能量在場內的流速，卻不能倒轉已經發生的事。古代核心也一樣。"),
        pilot("所以那些重複的回聲，不是過去的記錄？"),
        boss("是其他核心的回應。剩下的訊號正在彼此靠近……座標已同步，請繼續追查。"),
        pilot("時間場退出，機體時鐘正常。向下一站出發。"),
    )
    if(stage.number==11) return listOf(
        boss("夜匣投影關閉，貨艙解鎖。你的補給一件都沒少，信標上有完整記錄。"),
        pilot(if(cat==CatType.ORANGE)"橘曜只追有車轍的那一台。拆開貨艙，比追著全息影像跑有效。"else"玄影看見了掃描線，也看見磁索先鎖在哪裡。你騙不了同樣熟悉匿蹤的人。"),
        boss("我需要那些能源，是因為貨運網裡混進了一段古代訊號。它會模仿任何接近的武器。"),
        pilot("所以你用假車測試它？把貨單與訊號座標交出來。"),
        boss("資料已送出。吳哥的擬神系統就在那裡——別以為它只會複製一次。"),
        pilot("補給核對完成。夜匣保持停火，我們去處理回聲。"),
    )
    if(stage.number==12) return listOf(
        boss("擬神停止掃描，回放節點斷線。古代圖騰的第二道聲音……終於安靜了。"),
        pilot(if(cat==CatType.ORANGE)"橘曜看到掃描完成，就換了航線。你記住的是上一刻的火力，不是我的下一步。"else"玄影先拆回放節點，再等核心散熱。同樣的招式，我不需要躲第三次。"),
        boss("翼片變成雙臂，只是機械的變形。真正甦醒的，是核心裡那個會記憶的存在。"),
        pilot("它也回應了我們的貓族圖騰。所有訊號，正在指向同一個終點。"),
        boss("帶上這份掃描快照。最後的航路仍有守衛，但答案已經離你很近了。"),
        pilot("快照封存，核心穩定。繼續追查最後的訊號。"),
    )
    val report = when(stage.number) {
        1 -> "蜂群鏈路中斷，起司無人機全數返航。你的航跡，比雷達預測還快。"
        3 -> "重裝堡壘失去動力。能穿過這層裝甲，你的核心出力確實驚人。"
        4 -> "熱泉反應爐降壓完成。水霧散了，這條航路交給你。"
        5 -> "蘿蔔導彈解除武裝。下次見面，我會重新校準追蹤系統。"
        6 -> "冰層護盾碎裂，全艦停止射擊。南極通道准許通行。"
        7 -> "尤加防禦網離線。古老的訊號正在甦醒，你也聽見了吧。"
        8 -> "雙機同步已解除。能同時讀懂我們的航跡，算你厲害。"
        9 -> "竹節重砲歸位。力量可以擊穿護甲，克制才能守住核心。"
        10 -> "物流航道恢復……別催，座標正在傳送。重要的東西，要完整送達。"
        11 -> "匿蹤矩陣被你看穿了。這次就把航路密鑰當作見面禮。"
        12 -> "遺跡防衛機關休眠。你的紋章，與石壁上的記錄一模一樣。"
        else -> "地層探測陣列停機。訊號源比我們預想的還要深。"
    }
    return listOf(boss(report), pilot("火控解除。我們需要前往下一個核心訊號源，請開放航路。"),
        boss("導航資料已傳送。記住，核心回應的從來不只是力量。"),
        pilot(if(cat==CatType.ORANGE)"橘曜收到。裝甲重新同步，向下一站出發。" else "玄影收到。相位引擎就緒，開始下一段航行。"))
}
